//typecasting is used for converting float values to integer values and integer values to float
#include <iostream>
using namespace std;
int main() {
   int a=45;
   float b=45.46;
    //converting int a to float a 
    cout<<"The value of a is "<<float(a)<<endl;
    //converting float b to int b
    cout<<"The value of b is "<<int(b)<<endl;
    return 0;
}
