//printing 1-40 numbers using for loop
#include <iostream>
using namespace std;
int main() {
    for(int i=1; i<=40; i++){
        cout<<i<<endl;
    }
    return 0;
}

//printing 1-40 numbers using for loop
#include <iostream>
using namespace std;
int main() {
    int i=1;
    while(i<=40){
        cout<<i<<endl;
        i++;
        
    }
    return 0;
}
